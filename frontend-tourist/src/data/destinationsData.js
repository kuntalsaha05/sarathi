export function getDestinationById(id) {
  if (!id) return UNIVERSAL_DESTINATIONS[0];
  const found = UNIVERSAL_DESTINATIONS.find(d => d.id.toLowerCase() === id.toLowerCase() || d.name.toLowerCase() === id.toLowerCase());
  if (found) return found;
  return UNIVERSAL_DESTINATIONS[0];
}

export function searchDestinations(query) {
  if (!query || !query.trim()) return UNIVERSAL_DESTINATIONS;
  const q = query.toLowerCase().trim();
  return UNIVERSAL_DESTINATIONS.filter(d => 
    d.name.toLowerCase().includes(q) || 
    d.country.toLowerCase().includes(q) || 
    d.region.toLowerCase().includes(q) ||
    d.tagline.toLowerCase().includes(q)
  );
}

